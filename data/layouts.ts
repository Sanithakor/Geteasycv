export const getLayout = (id: string): Layout => {
  const layout = layouts.find((l) => l.id === id);
  if (!layout) {
    throw new Error(`Layout with id "${id}" not found`);
  }
  return layout;
};

export const getAllLayouts = (): Layout[] => layouts;

export const getLayoutsByCategory = (category: string): Layout[] => {
  return layouts.filter((l) => l.category === category);
};